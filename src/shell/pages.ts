/** Every HTML entry of the site. Used by the Vite build, the shell renderer and the tests. */
import { CITIES } from '../data/cities.ts';

/** Public address of the site (canonical links). */
export const SITE_URL = 'https://nioxxer.com';

export type PageId =
  | 'home'
  | 'search'
  | 'listing'
  | 'member'
  | 'login'
  | 'verifyEmail'
  | 'account'
  | 'publish'
  | 'boost'
  | 'admin'
  | 'help'
  | 'terms'
  | 'privacy'
  | 'legal'
  | 'rules'
  | 'notFound'
  | 'city';

export type NavTab = 'home' | 'search' | 'publish' | 'account';

export interface PageDef {
  readonly id: PageId;
  /** HTML file at the project root (Vite entry). */
  readonly file: string;
  /** Public clean URL (firebase.json `cleanUrls`). */
  readonly path: string;
  /** Bottom-bar tab highlighted on this page. */
  readonly nav: NavTab | null;
  readonly noindex: boolean;
  /** /ville/{slug} pages (generated by `npm run pages:sync`): the city shown. */
  readonly city?: { readonly slug: string; readonly name: string };
}

