/** Build entry name (unique, also for the 28 city pages). */
export function entryName(p: PageDef): string {
  return p.city ? `city-${p.city.slug}` : p.id;
}

export function pageByFile(file: string): PageDef | undefined {
  return PAGES.find((p) => p.file === file);
}

export function pageByPath(path: string): PageDef | undefined {
  return PAGES.find((p) => p.path === path);
}
